// Fast search: build an inverted index mapping lowercased keywords and tokens
export function buildTaxonomyIndex() {
  const keywordToSubdiscipline = new Map();

  for (const cat of KEYWORD_TAXONOMY) {
    for (const sub of cat.subdisciplines) {
      const entry = {
        category: cat.category,
        subdiscipline: sub.name,
        keywords: sub.keywords,
      };

      // Add subdiscipline name itself
      const subNameLower = sub.name.toLowerCase();
      keywordToSubdiscipline.set(subNameLower, entry);

      // Add all individual keywords
      for (const kw of sub.keywords) {
        keywordToSubdiscipline.set(kw.toLowerCase(), entry);
      }
    }
  }

  return keywordToSubdiscipline;
}

const TAXONOMY_INDEX = buildTaxonomyIndex();

/**
 * Searches the taxonomy for a query string.
 * Returns all matched subdisciplines and their categories with relevance tags.
 */
export function searchTaxonomy(query) {
  if (!query || typeof query !== "string") return [];
  const q = query.trim().toLowerCase();
  if (!q) return [];

  const matches = [];
  const seen = new Set();

  for (const cat of KEYWORD_TAXONOMY) {
    for (const sub of cat.subdisciplines) {
      const subNameLower = sub.name.toLowerCase();
      const matchedKeywords = sub.keywords.filter((kw) => {
        const kwLower = kw.toLowerCase();
        return kwLower.includes(q) || q.includes(kwLower);
      });

      const isSubMatch = subNameLower.includes(q);
      const isCatMatch = cat.category.toLowerCase().includes(q);

      if (isSubMatch || isCatMatch || matchedKeywords.length > 0) {
        if (!seen.has(sub.name)) {
          seen.add(sub.name);
          matches.push({
            category: cat.category,
            subdiscipline: sub.name,
            matchedKeywords: matchedKeywords.length > 0 ? matchedKeywords : sub.keywords.slice(0, 3),
            allKeywords: sub.keywords,
          });
        }
      }
    }
  }

  return matches;
}

